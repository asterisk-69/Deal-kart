export const searchProducts = (query) => {
  if (!query || typeof query !== 'string') return [];
  const q = query.trim().toLowerCase();
  if (q.length === 0) return products;

  return products.filter(p => {
    const nameMatch = p.name.toLowerCase().includes(q);
    const brandMatch = p.brand.toLowerCase().includes(q);
    const categoryMatch = p.category.toLowerCase().includes(q);
    const descMatch = (p.shortDescription || '').toLowerCase().includes(q);
    const tagMatch = Array.isArray(p.tags) && p.tags.some(t => t.toLowerCase().includes(q));
    const storageMatch = (p.storageVariant || '').toLowerCase().includes(q);
    const sellerMatch = p.sellers.some(s => s.sellerName.toLowerCase().includes(q));

    return nameMatch || brandMatch || categoryMatch || descMatch || tagMatch || storageMatch || sellerMatch;
  });
};
