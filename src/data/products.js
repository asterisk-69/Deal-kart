export const calculateFinalPrice = (sellerOffer) => {
  if (!sellerOffer) return 0;
  const price = Number(sellerOffer.price) || 0;
  const discount = Number(sellerOffer.discount) || 0;
  const deliveryCharge = Number(sellerOffer.deliveryCharge) || 0;
  return price - discount + deliveryCharge;
};

export const getSellerById = (id) => sellers.find(s => s.id === id);

export const getSortedSellersWithFinalPrice = (productSellers = []) => {
  return [...productSellers].map(s => {
    const sellerInfo = getSellerById(s.sellerId) || {};
    const finalPrice = calculateFinalPrice(s);
    return {
      ...s,
      sellerName: s.sellerName || sellerInfo.name || 'Seller',
      sellerInfo,
      finalPrice,
    };
  }).sort((a, b) => a.finalPrice - b.finalPrice);
};

export const getBestDealSeller = (product) => {
  if (!product || !product.sellers || product.sellers.length === 0) return null;
  const sorted = getSortedSellersWithFinalPrice(product.sellers);
  return sorted[0];
};

